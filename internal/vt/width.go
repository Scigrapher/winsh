package vt

// RuneWidth returns the number of terminal columns r occupies: 0 for
// combining/zero-width characters, 2 for East Asian wide and fullwidth
// characters, and 1 otherwise.
//
// The ranges below are the Unicode EastAsianWidth W and F sets that actually
// occur in shell and full-screen-program output, plus the emoji blocks that
// every current terminal renders double-width.
func RuneWidth(r rune) int {
	if r == 0 {
		return 1
	}
	if r < 0x20 || (r >= 0x7F && r < 0xA0) {
		return 1 // C0/C1 controls occupy a cell when forced through print()
	}
	if isZeroWidth(r) {
		return 0
	}
	if isWide(r) {
		return 2
	}
	return 1
}

func isZeroWidth(r rune) bool {
	switch {
	case r == 0x200B, r == 0x200C, r == 0x200D, r == 0xFEFF:
		return true
	case r >= 0x2000 && r <= 0x200F:
		return true
	case r >= 0x2060 && r <= 0x2064:
		return true
	case r >= 0x206A && r <= 0x206F:
		return true
	case r >= 0x180B && r <= 0x180E:
		return true
	case r >= 0xFFF9 && r <= 0xFFFB:
		return true
	}
	return isCombining(r)
}

