// isWide does a binary search over the sorted range table.
func isWide(r rune) bool {
	lo, hi := 0, len(wideRanges)-1
	for lo <= hi {
		mid := (lo + hi) / 2
		e := wideRanges[mid]
		switch {
		case r < e.lo:
			hi = mid - 1
		case r > e.hi:
			lo = mid + 1
		default:
			return true
		}
	}
	return false
}
